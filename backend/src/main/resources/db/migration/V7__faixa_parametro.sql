create table faixa_parametro (
    id            bigint        generated by default as identity primary key,
    modalidade    varchar(10)   not null check (modalidade in ('TENS', 'NMES', 'FES')),
    modo          varchar(40)   not null,
    parametro_id  bigint        not null references parametro_dicionario (id),
    origem        varchar(10)   not null check (origem in ('EDUCATIVA', 'APARELHO')),
    minimo        numeric(10, 2) not null,
    maximo        numeric(10, 2) not null,
    fonte         text          not null,
    constraint faixa_minimo_ate_maximo check (minimo <= maximo),
    constraint faixa_unica unique (modalidade, modo, parametro_id, origem)
);

alter table faixa_parametro enable row level security;

